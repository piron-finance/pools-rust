#[contract]
pub struct LockedPoolManager;

#[contractimpl]
impl LockedPoolManager {
    pub fn __constructor(
        env: Env,
        roles: Roles,
        escrow: Address,
        asset: Address,
        min_investment: i128,
        reserve: Option<Address>,
    ) {
        if let Some(r) = reserve {
            env.storage().instance().set(&DataKey::Reserve, &r);
        }
        env.storage().instance().set(&DataKey::Roles, &roles);
        env.storage().instance().set(&DataKey::Escrow, &escrow);
        env.storage().instance().set(&DataKey::Asset, &asset);
        env.storage()
            .instance()
            .set(&DataKey::MinInvestment, &min_investment);
        env.storage().instance().set(&DataKey::IsActive, &true);
        env.storage()
            .instance()
            .set(&DataKey::Tiers, &Vec::<StoredTier>::new(&env));
        env.storage()
            .instance()
            .set(&DataKey::Metrics, &StoredMetrics::empty());
        env.storage().instance().set(&DataKey::NextPositionId, &1u64);
        bump_instance(&env);
    }

    // ------------------------------------------------------------ tiers

    /// Adds a tenor to the table. Existing positions keep the rate they were struck at.
    pub fn add_tier(env: Env, caller: Address, tier: StoredTier) -> Result<u32, Error> {
        Self::require_admin(&env, &caller)?;
        validate::validate_tier(&tier.to_core())?;

        let mut tiers = Self::tiers(&env);
        tiers.push_back(tier.clone());
        let index = tiers.len() - 1;
        env.storage().instance().set(&DataKey::Tiers, &tiers);

        TierAdded {
            tier_index: index,
            duration_days: tier.duration_days,
            apy_bps: tier.apy_bps,
        }
        .publish(&env);
        Ok(index)
    }

    /// Opens or closes a tenor to new deposits.
    pub fn set_tier_active(
        env: Env,
        caller: Address,
        tier_index: u32,
        is_active: bool,
    ) -> Result<(), Error> {
        Self::require_admin(&env, &caller)?;
        let mut tiers = Self::tiers(&env);
        let mut tier = tiers.get(tier_index).ok_or(Error::InvalidTier)?;
        tier.is_active = is_active;
        tiers.set(tier_index, tier);
        env.storage().instance().set(&DataKey::Tiers, &tiers);
        Ok(())
    }

    pub fn tier_count(env: Env) -> u32 {
        Self::tiers(&env).len()
    }

    pub fn tier(env: Env, tier_index: u32) -> Result<StoredTier, Error> {
        Self::tiers(&env).get(tier_index).ok_or(Error::InvalidTier)
    }

    // ------------------------------------------------------------ deposits

    /// Locks `amount` for the term of `tier_index`, at that tier's current rate.
    pub fn deposit(
        env: Env,
        investor: Address,
        amount: i128,
        tier_index: u32,
        payment_choice: u32,
    ) -> Result<u64, Error> {
        investor.require_auth();
        bump_instance(&env);
        Self::require_open(&env)?;

        let tiers = Self::tiers(&env);
        let tier = tiers.get(tier_index).ok_or(Error::InvalidTier)?.to_core();
        validate::validate_deposit(amount, tier_index, &tier, tiers.len())?;

        let min: i128 = env
            .storage()
            .instance()
            .get(&DataKey::MinInvestment)
            .unwrap_or(0);
        if amount < min {
            return Err(Error::BelowMinInvestment);
        }

        let payment = storage::payment_from_u32(payment_choice);
        let now = env.ledger().timestamp();
        let interest = calc::interest_for_term(amount, tier.apy_bps, tier.duration_days)?;
        if payment == lt::InterestPayment::Upfront {
            validate::validate_upfront_capacity(amount, interest)?;
        }

        let position = calc::build_position(amount, &tier, tier_index, payment, now)?;

        // Principal into custody first.
        let escrow = Self::escrow(&env)?;
        escrow.take(&investor, &amount);
        // An upfront position pays its interest out immediately, which is why only the
        // remainder is ever put to work.
        if payment == lt::InterestPayment::Upfront && position.full_interest_amount > 0 {
            escrow.release(&investor, &position.full_interest_amount);
        }

        let id = Self::next_id(&env);
        write_position(&env, id, &StoredPosition::from_core(investor.clone(), &position));

        let mut metrics = Self::metrics(&env);
        metrics.total_principal_locked = storage::saturating_add(
            metrics.total_principal_locked,
            position.principal_deposited,
        );
        metrics.total_interest_committed = storage::saturating_add(
            metrics.total_interest_committed,
            position.full_interest_amount,
        );
        match payment {
            lt::InterestPayment::Upfront => {
                metrics.total_interest_paid_upfront = storage::saturating_add(
                    metrics.total_interest_paid_upfront,
                    position.full_interest_amount,
                )
            }
            lt::InterestPayment::AtMaturity => {
                metrics.interest_pending_maturity = storage::saturating_add(
                    metrics.interest_pending_maturity,
                    position.full_interest_amount,
                )
            }
        }
        metrics.active_positions += 1;
        metrics.total_positions += 1;
        env.storage().instance().set(&DataKey::Metrics, &metrics);

        PositionOpened {
            owner: investor,
            position_id: id,
            principal: amount,
            interest: position.full_interest_amount,
            lock_end: position.lock_end,
        }
        .publish(&env);
        Ok(id)
    }

    // ------------------------------------------------------------ exits

    /// Redeems a matured position.
    pub fn redeem(env: Env, owner: Address, position_id: u64) -> Result<i128, Error> {
        owner.require_auth();
        bump_instance(&env);

        let mut stored = Self::owned_position(&env, &owner, position_id)?;
        let redemption = lifecycle::redeem(&stored.to_core(), env.ledger().timestamp())?;

        stored.status = storage::status_to_u32(redemption.new_status);
        stored.actual_payout = redemption.payout;
        stored.interest_earned = storage::saturating_add(
            stored.interest_earned,
            redemption.interest_component,
        );
        write_position(&env, position_id, &stored);

        Self::escrow(&env)?.release(&owner, &redemption.payout);
        Self::close_position_metrics(&env, stored.principal_deposited);

        PositionRedeemed {
            owner,
            position_id,
            payout: redemption.payout,
        }
        .publish(&env);
        Ok(redemption.payout)
    }

    /// Leaves a position before maturity, paying the tier's penalty.
    pub fn exit_early(env: Env, owner: Address, position_id: u64) -> Result<i128, Error> {
        owner.require_auth();
        bump_instance(&env);

        let mut stored = Self::owned_position(&env, &owner, position_id)?;
        let tier = Self::tiers(&env)
            .get(stored.tier_index)
            .ok_or(Error::InvalidTier)?
            .to_core();

        let exit = lifecycle::exit_early(&stored.to_core(), &tier, env.ledger().timestamp())?;

        stored.status = storage::status_to_u32(exit.new_status);
        stored.actual_payout = exit.payout;
        stored.penalty_paid = exit.penalty;
        write_position(&env, position_id, &stored);

        let escrow = Self::escrow(&env)?;

        // The payout carries interest accrued to today, and the escrow holds only the
        // principal until the SPV returns yield. So an exit is normally short by exactly
        // the interest earned, and without cover it fails — the ordinary case, not an
        // edge one. The yield reserve lends the difference and the pool owes it back.
        let needed = exit.payout.saturating_add(exit.penalty);
        let held = escrow.balance();
        if needed > held {
            Self::borrow_from_reserve(&env, needed - held)?;
        }

        if exit.payout > 0 {
            escrow.release(&owner, &exit.payout);
        }
        // The penalty stays with the protocol rather than the pool, which is what makes
        // early exit fund the reserve instead of subsidising the remaining holders.
        if exit.penalty > 0 {
            escrow.release(&Self::roles(&env)?.treasury, &exit.penalty);
        }
        Self::close_position_metrics(&env, stored.principal_deposited);

        PositionExitedEarly {
            owner,
            position_id,
            payout: exit.payout,
            penalty: exit.penalty,
        }
        .publish(&env);
        Ok(exit.payout)
    }

    /// Re-locks a matured position into another term without the money leaving.
    pub fn roll_over(
        env: Env,
        owner: Address,
        position_id: u64,
        tier_index: u32,
        payment_choice: u32,
    ) -> Result<u64, Error> {
        owner.require_auth();
        bump_instance(&env);
        Self::require_open(&env)?;

        let mut stored = Self::owned_position(&env, &owner, position_id)?;
        let tier = Self::tiers(&env)
            .get(tier_index)
            .ok_or(Error::InvalidTier)?
            .to_core();

        let roll = lifecycle::roll_over(
            &stored.to_core(),
            &tier,
            tier_index,
            storage::payment_from_u32(payment_choice),
            env.ledger().timestamp(),
        )?;

        stored.status = storage::status_to_u32(roll.closed_status);
        write_position(&env, position_id, &stored);

        let new_id = Self::next_id(&env);
        write_position(
            &env,
            new_id,
            &StoredPosition::from_core(owner.clone(), &roll.new_position),
        );

        // An upfront rollover still pays its interest out on day one.
        if roll.new_position.interest_paid && roll.new_position.full_interest_amount > 0 {
            Self::escrow(&env)?.release(&owner, &roll.new_position.full_interest_amount);
        }

        let mut metrics = Self::metrics(&env);
        metrics.total_positions += 1;
        env.storage().instance().set(&DataKey::Metrics, &metrics);

        PositionRolledOver {
            owner,
            old_position_id: position_id,
            new_position_id: new_id,
            principal: roll.principal_rolled,
        }
        .publish(&env);
        Ok(new_id)
    }

    // ------------------------------------------------------------ spv

    /// Sends idle capital to the SPV.
    ///
    /// The whole balance is drawable. Holding back principal plus the interest owed would
    /// leave the pool nothing to invest, and the yield paying the promised APY has to come
    /// from somewhere; a maturity is met out of what the SPV returns, and an exit that
    /// lands before then is covered by the reserve.
    pub fn deploy_to_spv(env: Env, caller: Address, amount: i128) -> Result<(), Error> {
        Self::require_spv(&env, &caller)?;
        if amount <= 0 {
            return Err(Error::InvalidAmount);
        }
        if amount > Self::deployable(env.clone()) {
            return Err(Error::InsufficientLiquidity);
        }

        Self::escrow(&env)?.release(&caller, &amount);
        let mut metrics = Self::metrics(&env);
        metrics.total_invested = storage::saturating_add(metrics.total_invested, amount);
        env.storage().instance().set(&DataKey::Metrics, &metrics);

        CapitalDeployed { amount }.publish(&env);
        Ok(())
    }

    /// Returns capital or yield from the SPV.
    pub fn return_from_spv(env: Env, caller: Address, amount: i128) -> Result<(), Error> {
        Self::require_spv(&env, &caller)?;
        if amount <= 0 {
            return Err(Error::InvalidAmount);
        }

        Self::escrow(&env)?.take(&caller, &amount);
        let mut metrics = Self::metrics(&env);
        // Returns retire deployed capital first; anything beyond it is yield.
        metrics.total_invested = (metrics.total_invested - amount).max(0);
        env.storage().instance().set(&DataKey::Metrics, &metrics);

        CapitalReturned { amount }.publish(&env);
        Ok(())
    }

    fn escrow_address(env: &Env) -> Result<Address, Error> {
        env.storage()
            .instance()
            .get(&DataKey::Escrow)
            .ok_or(Error::NotInitialized)
    }

    /// Draws `amount` from the yield reserve into the escrow and records the debt.
    fn borrow_from_reserve(env: &Env, amount: i128) -> Result<(), Error> {
        let reserve: Address = env
            .storage()
            .instance()
            .get(&DataKey::Reserve)
            .ok_or(Error::NoYieldReserve)?;

        ReserveClient::new(env, &reserve).loan_to_pool(
            &env.current_contract_address(),
            &env.current_contract_address(),
            &Self::escrow_address(env)?,
            &amount,
        );

        let owed = Self::pool_debt(env.clone()).saturating_add(amount);
        env.storage().instance().set(&DataKey::Debt, &owed);
        ReserveBorrowed { amount, outstanding: owed }.publish(env);
        Ok(())
    }

    /// What the pool owes the yield reserve for early exits it could not cover.
    pub fn pool_debt(env: Env) -> i128 {
        env.storage().instance().get(&DataKey::Debt).unwrap_or(0)
    }

    /// Repays the reserve out of the SPV's own funds.
    ///
    /// The SPV holds the returned capital and the yield it earned, so it is the party that
    /// can settle. Leaving the debt outstanding would have the reserve quietly subsidising
    /// this pool's holders at every other pool's expense.
    pub fn settle_debt(env: Env, caller: Address, amount: i128) -> Result<(), Error> {
        Self::require_spv(&env, &caller)?;
        if amount <= 0 {
            return Err(Error::InvalidAmount);
        }
        let owed = Self::pool_debt(env.clone());
        if amount > owed {
            return Err(Error::InvalidAmount);
        }

        let reserve: Address = env
            .storage()
            .instance()
            .get(&DataKey::Reserve)
            .ok_or(Error::NoYieldReserve)?;
        ReserveClient::new(&env, &reserve).repay_loan(
            &caller,
            &env.current_contract_address(),
            &amount,
        );

        let remaining = owed - amount;
        env.storage().instance().set(&DataKey::Debt, &remaining);
        ReserveRepaid { amount, outstanding: remaining }.publish(&env);
        Ok(())
    }

    /// Cash the SPV may draw to invest.
    ///
    /// This used to hold back principal plus the interest owed at maturity, on the
    /// reasoning that promised payouts must stay covered at all times. The reasoning is
    /// wrong, and wrong in a way that makes the product impossible: the escrow only ever
    /// holds the principal, so a pool that must also cover the interest can never release
    /// anything, and a locked pool exists precisely to have that principal invested. The
    /// yield that pays the promised APY has to come from somewhere.
    ///
    /// The obligation is met at maturity, out of what the SPV returns — capital plus the
    /// yield it earned. An early exit that outruns the escrow is what the yield reserve
    /// backstops. This matches `createPendingAllocation` in the Solidity, which lets the
    /// SPV draw up to the principal held.
    pub fn deployable(env: Env) -> i128 {
        Self::escrow(&env).map(|e| e.balance()).unwrap_or(0).max(0)
    }

    // ------------------------------------------------------------ views

    pub fn position(env: Env, position_id: u64) -> Result<StoredPosition, Error> {
        read_position(&env, position_id).ok_or(Error::PositionNotFound)
    }

    /// Interest accrued so far, the days left, and whether the holder may act.
    pub fn position_value(env: Env, position_id: u64) -> Result<i128, Error> {
        let stored = read_position(&env, position_id).ok_or(Error::PositionNotFound)?;
        let summary = calc::position_summary(&stored.to_core(), env.ledger().timestamp())?;
        Ok(summary.interest_amount)
    }

    pub fn days_remaining(env: Env, position_id: u64) -> Result<u64, Error> {
        let stored = read_position(&env, position_id).ok_or(Error::PositionNotFound)?;
        Ok(calc::days_remaining(stored.lock_end, env.ledger().timestamp()))
    }

    /// What leaving now would pay, before it is committed.
    pub fn quote_early_exit(env: Env, position_id: u64) -> Result<i128, Error> {
        let stored = read_position(&env, position_id).ok_or(Error::PositionNotFound)?;
        let tier = Self::tiers(&env)
            .get(stored.tier_index)
            .ok_or(Error::InvalidTier)?
            .to_core();
        Ok(calc::early_exit(&stored.to_core(), &tier, env.ledger().timestamp())?.payout)
    }

    pub fn metrics(env: &Env) -> StoredMetrics {
        env.storage()
            .instance()
            .get(&DataKey::Metrics)
            .unwrap_or(StoredMetrics::empty())
    }

    pub fn pool_metrics(env: Env) -> StoredMetrics {
        Self::metrics(&env)
    }

    /// Closes the pool to new deposits. Existing positions run to term regardless.
    pub fn set_active(env: Env, caller: Address, is_active: bool) -> Result<(), Error> {
        Self::require_admin(&env, &caller)?;
        env.storage().instance().set(&DataKey::IsActive, &is_active);
        Ok(())
    }

    // ------------------------------------------------------------ internals

    fn tiers(env: &Env) -> Vec<StoredTier> {
        env.storage()
            .instance()
            .get(&DataKey::Tiers)
            .unwrap_or(Vec::new(env))
    }

    fn next_id(env: &Env) -> u64 {
        let id: u64 = env
            .storage()
            .instance()
            .get(&DataKey::NextPositionId)
            .unwrap_or(1);
        env.storage()
            .instance()
            .set(&DataKey::NextPositionId, &(id + 1));
        id
    }

    fn owned_position(
        env: &Env,
        owner: &Address,
        position_id: u64,
    ) -> Result<StoredPosition, Error> {
        let stored = read_position(env, position_id).ok_or(Error::PositionNotFound)?;
        if stored.owner != *owner {
            return Err(Error::NotPositionOwner);
        }
        Ok(stored)
    }

    fn close_position_metrics(env: &Env, principal: i128) {
        let mut metrics = Self::metrics(env);
        metrics.total_principal_locked =
            metrics.total_principal_locked.saturating_sub(principal);
        if metrics.active_positions > 0 {
            metrics.active_positions -= 1;
        }
        env.storage().instance().set(&DataKey::Metrics, &metrics);
    }

    fn escrow(env: &Env) -> Result<EscrowClient<'_>, Error> {
        let address: Address = env
            .storage()
            .instance()
            .get(&DataKey::Escrow)
            .ok_or(Error::NotInitialized)?;
        Ok(EscrowClient::new(env, &address))
    }

    fn roles(env: &Env) -> Result<Roles, Error> {
        env.storage()
            .instance()
            .get(&DataKey::Roles)
            .ok_or(Error::NotInitialized)
    }

    fn require_spv(env: &Env, caller: &Address) -> Result<(), Error> {
        caller.require_auth();
        bump_instance(env);
        if *caller != Self::roles(env)?.spv {
            return Err(Error::Unauthorized);
        }
        Ok(())
    }

    fn require_admin(env: &Env, caller: &Address) -> Result<(), Error> {
        caller.require_auth();
        bump_instance(env);
        if *caller != Self::roles(env)?.admin {
            return Err(Error::Unauthorized);
        }
        Ok(())
    }

    fn require_open(env: &Env) -> Result<(), Error> {
        let active: bool = env
            .storage()
            .instance()
            .get(&DataKey::IsActive)
            .unwrap_or(false);
        if !active {
            return Err(Error::PoolClosed);
        }
        Ok(())
    }
}


// ---------------------------------------------------------------- upgrades
//
// Soroban contracts replace their own bytecode; there is no proxy. So each one names an
// upgrader once — in production the timelock — and only that address can swap the code.
// The 72-hour delay and the guardian's brake live there, in front of every upgrade in the
// system.

#[contractimpl]
impl LockedPoolManager {
    /// Names the contract permitted to upgrade this one. Callable once.
    ///
    /// One-way on purpose: a contract whose upgrader could be repointed has no timelock,
    /// only the appearance of one.
    pub fn bind_upgrader(env: Env, caller: Address, upgrader: Address) -> Result<(), Error> {
        Self::require_admin(&env, &caller)?;
        piron_types::upgradeable::bind(&env, &upgrader).map_err(|_| Error::AlreadyBound)
    }

    /// Replaces this contract's code. Only the bound upgrader may call it.
    pub fn upgrade(env: Env, wasm_hash: soroban_sdk::BytesN<32>) -> Result<(), Error> {
        piron_types::upgradeable::perform(&env, wasm_hash).map_err(|e| match e {
            piron_types::upgradeable::UpgradeError::NotBound => Error::NotInitialized,
            piron_types::upgradeable::UpgradeError::AlreadyBound => Error::AlreadyBound,
        })
    }

    /// Who may upgrade this contract, if anyone yet.
    pub fn upgrader(env: Env) -> Option<Address> {
        piron_types::upgradeable::upgrader(&env)
    }
}

