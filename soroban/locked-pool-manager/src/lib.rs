//! Locked (fixed-term) pool manager — Soroban binding.
//!
//! Ported from `src/LockedPoolManager.sol`. Every rule lives in
//! `piron_core::locked`; this crate stores positions, checks signatures, moves tokens
//! through the escrow and emits events.
//!
//! The shape differs from Single Asset: there is no single deal, so there is no pool-wide
//! status machine. Each deposit is its own position with its own term and rate, and the
//! pool is just the tier table plus the running totals.

