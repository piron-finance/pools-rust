//! Stable Yield pool manager — Soroban binding.
//!
//! Ported from `src/StableYieldManager.sol`. Deposits and withdrawals are priced against
//! NAV, so unlike the other two pool types the share price moves — a depositor buys in at
//! whatever the portfolio is worth today.
//!
//! The withdrawal queue is the one place where this binding deliberately does not mirror
//! the Solidity's control flow. There, processing walks the whole queue in one call. Here
//! it settles a bounded batch and advances a cursor, because a Soroban transaction
//! declares its ledger footprint up front and an unbounded walk cannot.

