/// The pool's share token. Holdings live there, not in this contract's storage, so a
/// position can be transferred, custodied or posted as collateral.
#[contractclient(name = "ShareClient")]
pub trait Share {
    fn mint(env: Env, to: Address, amount: i128);
    fn burn(env: Env, from: Address, amount: i128);
    fn balance(env: Env, id: Address) -> i128;
    fn total_supply(env: Env) -> i128;
}

#[contract]
pub struct StableYieldManager;

#[contractimpl]
impl StableYieldManager {
    pub fn __constructor(
        env: Env,
        roles: Roles,
        escrow: Address,
        asset: Address,
        config: Config,
        share: Address,
    ) {
        env.storage().instance().set(&DataKey::Roles, &roles);
        env.storage().instance().set(&DataKey::Escrow, &escrow);
        env.storage().instance().set(&DataKey::Asset, &asset);
        env.storage().instance().set(&DataKey::Config, &config);
        env.storage().instance().set(&DataKey::Share, &share);
        env.storage()
            .instance()
            .set(&DataKey::Instruments, &Vec::<StoredInstrument>::new(&env));
        env.storage().instance().set(&DataKey::QueueHead, &0u64);
        env.storage().instance().set(&DataKey::QueueTail, &0u64);
        env.storage().instance().set(&DataKey::QueuePending, &0i128);
        env.storage()
            .instance()
            .set(&DataKey::DeployedOutstanding, &0i128);
        bump_instance(&env);
    }

    // ------------------------------------------------------------ pricing

    /// Everything the pool is worth: instruments marked to model, plus escrow cash.
    pub fn total_nav(env: Env) -> Result<i128, Error> {
        let gross = Self::gross_asset_value(&env)?;
        let reserves = Self::escrow(&env)?.balance();
        // Capital in flight counts too: it left the escrow but still belongs to the pool.
        let in_flight = Self::deployed_outstanding(&env);
        Ok(nav::pool_nav(gross, reserves)?
            .checked_add(in_flight)
            .ok_or(Error::Overflow)?)
    }

    /// Price of one share, scaled by 1e18.
    pub fn nav_per_share(env: Env) -> Result<i128, Error> {
        let total = Self::total_nav(env.clone())?;
        Ok(nav::nav_per_share(total, Self::total_shares(&env))?)
    }

    // ------------------------------------------------------------ deposits

    /// Buys into the pool at today's price.
    pub fn deposit(env: Env, investor: Address, assets: i128) -> Result<i128, Error> {
        investor.require_auth();
        bump_instance(&env);

        let config = Self::config(&env)?;
        validate::validate_deposit(assets, config.min_investment, config.is_active)?;

        // Priced before the assets arrive, or the depositor would be buying shares in
        // their own deposit.
        let price = Self::nav_per_share(env.clone())?;
        let shares = nav::shares_for_deposit(assets, price)?;

        Self::escrow(&env)?.take(&investor, &assets);

        Self::share(&env)?.mint(&investor, &shares);

        // First deposit starts the holding-period clock; later ones do not restart it.
        let key = DataKey::DepositTime(investor.clone());
        if !env.storage().persistent().has(&key) {
            env.storage()
                .persistent()
                .set(&key, &env.ledger().timestamp());
        }

        Deposit {
            receiver: investor,
            assets,
            shares,
            nav_per_share: price,
        }
        .publish(&env);
        Ok(shares)
    }

    // ------------------------------------------------------------ withdrawals

    /// Joins the queue to leave. Shares are held until the request is served.
    pub fn request_withdrawal(env: Env, owner: Address, shares: i128) -> Result<u64, Error> {
        owner.require_auth();
        bump_instance(&env);

        let config = Self::config(&env)?;
        let held = Self::held_by(&env, &owner);
        validate::validate_withdrawal_request(shares, held)?;

        let deposit_time: u64 = env
            .storage()
            .persistent()
            .get(&DataKey::DepositTime(owner.clone()))
            .unwrap_or(0);
        validate::validate_holding_period(
            deposit_time,
            config.holding_period,
            env.ledger().timestamp(),
        )?;

        let price = Self::nav_per_share(env.clone())?;
        let quote = queue::quote_withdrawal(shares, price, config.withdrawal_fee_bps)?;

        let index: u64 = env.storage().instance().get(&DataKey::QueueTail).unwrap_or(0);
        write_request(
            &env,
            index,
            &StoredRequest {
                owner: owner.clone(),
                shares,
                request_time: env.ledger().timestamp(),
                deadline: 0,
                estimated_value: quote.net_value,
                fee_amount: quote.fee,
                processed: false,
                processed_time: 0,
            },
        );
        env.storage()
            .instance()
            .set(&DataKey::QueueTail, &(index + 1));

        let pending: i128 = env
            .storage()
            .instance()
            .get(&DataKey::QueuePending)
            .unwrap_or(0);
        env.storage()
            .instance()
            .set(&DataKey::QueuePending, &(pending + quote.net_value));

        WithdrawalRequested {
            owner,
            request_id: index,
            shares,
            estimated_value: quote.net_value,
        }
        .publish(&env);
        Ok(index)
    }

    /// Settles up to `max_items` queued exits, in order, from free cash.
    ///
    /// Free cash means escrow balance above the reserve floor — a pool must not empty
    /// itself serving the queue and leave nothing for the next redemption.
    pub fn process_withdrawals(
        env: Env,
        caller: Address,
        max_items: u32,
    ) -> Result<u32, Error> {
        Self::require_operator(&env, &caller)?;

        let config = Self::config(&env)?;
        let head: u64 = env.storage().instance().get(&DataKey::QueueHead).unwrap_or(0);
        let tail: u64 = env.storage().instance().get(&DataKey::QueueTail).unwrap_or(0);

        let total_nav = Self::total_nav(env.clone())?;
        let reserves = Self::escrow(&env)?.balance();
        let available = validate::deployable_amount(reserves, total_nav, &config.reserve())?;
        let price = nav::nav_per_share(total_nav, Self::total_shares(&env))?;

        // Load only the slice this batch may touch, so the footprint is known up front.
        let slice = piron_core::stable_yield::types::WithdrawalQueue {
            head,
            tail,
            total_pending_value: 0,
        };
        let mut owners = Vec::new(&env);
        let mut requests_buf: [piron_core::stable_yield::types::WithdrawalRequest;
            queue::MAX_WITHDRAWAL_BATCH as usize] = [piron_core::stable_yield::types::WithdrawalRequest {
            shares: 0,
            request_time: 0,
            deadline: 0,
            estimated_value: 0,
            fee_amount: 0,
            processed: true,
            processed_time: 0,
        }; queue::MAX_WITHDRAWAL_BATCH as usize];

        let take = core::cmp::min(max_items, queue::MAX_WITHDRAWAL_BATCH);
        let mut loaded = 0usize;
        for offset in 0..take as u64 {
            if head + offset >= tail {
                break;
            }
            match read_request(&env, head + offset) {
                Some(r) => {
                    requests_buf[loaded] = r.to_core();
                    owners.push_back(r.owner);
                    loaded += 1;
                }
                None => break,
            }
        }

        let outcome = queue::process_batch(
            &slice,
            &requests_buf[..loaded],
            available,
            price,
            config.withdrawal_fee_bps,
            take,
        )?;

        // Pay out and settle each request the batch covered.
        let escrow = Self::escrow(&env)?;
        for i in 0..outcome.processed as u64 {
            let index = head + i;
            if let Some(mut stored) = read_request(&env, index) {
                if stored.processed {
                    continue;
                }
                let quote =
                    queue::quote_withdrawal(stored.shares, price, config.withdrawal_fee_bps)?;

                Self::share(&env)?.burn(&stored.owner, &stored.shares);

                escrow.release(&stored.owner, &quote.net_value);
                if quote.fee > 0 {
                    escrow.release(&Self::roles(&env)?.treasury, &quote.fee);
                }

                stored.processed = true;
                stored.processed_time = env.ledger().timestamp();
                write_request(&env, index, &stored);
            }
        }

        env.storage()
            .instance()
            .set(&DataKey::QueueHead, &outcome.new_head);

        let pending: i128 = env
            .storage()
            .instance()
            .get(&DataKey::QueuePending)
            .unwrap_or(0);
        env.storage().instance().set(
            &DataKey::QueuePending,
            &(pending - outcome.total_paid).max(0),
        );

        WithdrawalsProcessed {
            processed: outcome.processed,
            total_paid: outcome.total_paid,
            new_head: outcome.new_head,
            stopped_for_liquidity: outcome.stopped_for_liquidity,
        }
        .publish(&env);
        Ok(outcome.processed)
    }

    pub fn queue_length(env: Env) -> u64 {
        let head: u64 = env.storage().instance().get(&DataKey::QueueHead).unwrap_or(0);
        let tail: u64 = env.storage().instance().get(&DataKey::QueueTail).unwrap_or(0);
        tail.saturating_sub(head)
    }

    // ------------------------------------------------------------ portfolio

    /// Records an instrument the manager has bought.
    pub fn add_instrument(
        env: Env,
        caller: Address,
        instrument: StoredInstrument,
    ) -> Result<u32, Error> {
        Self::require_operator(&env, &caller)?;

        let mut instruments = Self::instruments(&env);
        if instruments.len() >= MAX_INSTRUMENTS {
            return Err(Error::TooManyInstruments);
        }
        // An instrument is bought with capital already drawn. Recording one larger than
        // what is in flight would clamp the balance at zero and leave NAV counting the
        // holding in full — value the pool never had.
        if instrument.purchase_price > Self::deployed_outstanding(&env) {
            return Err(Error::ExceedsInFlight);
        }
        if instrument.instrument_type != 0 {
            if instrument.coupon_frequency == 0 || instrument.coupon_frequency > MAX_COUPON_FREQUENCY
            {
                return Err(Error::InvalidCouponFrequency);
            }
            if instrument.annual_coupon_rate == 0
                || instrument.annual_coupon_rate > MAX_ANNUAL_COUPON_RATE
            {
                return Err(Error::InvalidCouponRate);
            }
        }
        instruments.push_back(instrument.clone());
        let index = instruments.len() - 1;
        env.storage()
            .instance()
            .set(&DataKey::Instruments, &instruments);

        // Recording what was bought converts in-flight capital into a holding.
        Self::set_deployed(
            &env,
            Self::deployed_outstanding(&env) - instrument.purchase_price,
        );

        InstrumentAdded {
            index,
            face_value: instrument.face_value,
            maturity_date: instrument.maturity_date,
        }
        .publish(&env);
        Self::emit_nav(&env)?;
        Ok(index)
    }

    /// Records a coupon paid on a holding.
    ///
    /// The cash comes into the escrow and the instrument's clock advances, so NAV stops
    /// accruing the coupon it has now actually received and starts accruing the next one.
    pub fn record_instrument_coupon(
        env: Env,
        caller: Address,
        index: u32,
        amount: i128,
    ) -> Result<(), Error> {
        Self::require_spv(&env, &caller)?;
        if amount <= 0 {
            return Err(Error::InvalidAmount);
        }

        let mut instruments = Self::instruments(&env);
        let mut instrument = instruments.get(index).ok_or(Error::InstrumentNotFound)?;
        if !instrument.is_active {
            return Err(Error::InstrumentNotFound);
        }
        if instrument.coupon_frequency == 0 {
            return Err(Error::InvalidCouponFrequency);
        }

        Self::escrow(&env)?.take(&caller, &amount);

        let period = nav::SECONDS_PER_YEAR / instrument.coupon_frequency as u64;
        instrument.coupons_paid += 1;
        instrument.next_coupon_due_date = instrument.next_coupon_due_date.saturating_add(period);
        instruments.set(index, instrument.clone());
        env.storage()
            .instance()
            .set(&DataKey::Instruments, &instruments);

        CouponReceived {
            index,
            amount,
            coupons_paid: instrument.coupons_paid,
        }
        .publish(&env);
        Self::emit_nav(&env)
    }

    /// Settles a holding at maturity: the proceeds come back and the instrument closes.
    ///
    /// A return short of face value is accepted and shows up as a NAV fall — the pool
    /// took a loss, and pretending otherwise would misprice every share.
    pub fn mature_instrument(
        env: Env,
        caller: Address,
        index: u32,
        proceeds: i128,
    ) -> Result<(), Error> {
        Self::require_spv(&env, &caller)?;
        if proceeds <= 0 {
            return Err(Error::InvalidAmount);
        }

        let mut instruments = Self::instruments(&env);
        let mut instrument = instruments.get(index).ok_or(Error::InstrumentNotFound)?;
        if !instrument.is_active {
            return Err(Error::InstrumentNotFound);
        }

        Self::escrow(&env)?.take(&caller, &proceeds);
        instrument.is_active = false;
        instruments.set(index, instrument.clone());
        env.storage()
            .instance()
            .set(&DataKey::Instruments, &instruments);

        InstrumentMatured {
            index,
            proceeds,
            face_value: instrument.face_value,
        }
        .publish(&env);
        Self::emit_nav(&env)
    }

    /// Closes out an instrument that has matured or been sold.
    pub fn close_instrument(env: Env, caller: Address, index: u32) -> Result<(), Error> {
        Self::require_operator(&env, &caller)?;
        let mut instruments = Self::instruments(&env);
        let mut instrument = instruments.get(index).ok_or(Error::InstrumentNotFound)?;
        instrument.is_active = false;
        instruments.set(index, instrument);
        env.storage()
            .instance()
            .set(&DataKey::Instruments, &instruments);
        Self::emit_nav(&env)
    }

    pub fn instrument_count(env: Env) -> u32 {
        Self::instruments(&env).len()
    }

    /// Sends free cash to an SPV, leaving the reserve intact.
    pub fn deploy_capital(env: Env, caller: Address, amount: i128) -> Result<(), Error> {
        Self::require_spv(&env, &caller)?;

        let config = Self::config(&env)?;
        let total_nav = Self::total_nav(env.clone())?;
        let reserves = Self::escrow(&env)?.balance();
        validate::validate_deployment(amount, reserves, total_nav, &config.reserve())?;

        Self::escrow(&env)?.release(&caller, &amount);
        Self::set_deployed(&env, Self::deployed_outstanding(&env) + amount);
        Self::emit_nav(&env)
    }

    /// Returns capital or yield from an SPV into the pool.
    pub fn return_capital(env: Env, caller: Address, amount: i128) -> Result<(), Error> {
        Self::require_spv(&env, &caller)?;
        if amount <= 0 {
            return Err(Error::InvalidAmount);
        }
        Self::escrow(&env)?.take(&caller, &amount);
        // Returns retire in-flight capital first; anything beyond it is yield, which
        // shows up as a NAV gain rather than reducing the outstanding balance below zero.
        Self::set_deployed(&env, (Self::deployed_outstanding(&env) - amount).max(0));
        Self::emit_nav(&env)
    }

    /// Cash free to deploy without breaching the reserve.
    pub fn deployable(env: Env) -> Result<i128, Error> {
        let config = Self::config(&env)?;
        let total_nav = Self::total_nav(env.clone())?;
        let reserves = Self::escrow(&env)?.balance();
        Ok(validate::deployable_amount(
            reserves,
            total_nav,
            &config.reserve(),
        )?)
    }

    // ------------------------------------------------------------ views

    pub fn shares_of(env: Env, who: Address) -> i128 {
        Self::held_by(&env, &who)
    }

    pub fn share_token(env: Env) -> Result<Address, Error> {
        env.storage()
            .instance()
            .get(&DataKey::Share)
            .ok_or(Error::NotInitialized)
    }

    pub fn total_supply(env: Env) -> i128 {
        Self::total_shares(&env)
    }

    /// What a holder's stake is worth at today's price.
    pub fn holding_value(env: Env, who: Address) -> Result<i128, Error> {
        let price = Self::nav_per_share(env.clone())?;
        Ok(nav::assets_for_shares(Self::held_by(&env, &who), price)?)
    }

    // ------------------------------------------------------------ internals

    fn gross_asset_value(env: &Env) -> Result<i128, Error> {
        let stored = Self::instruments(env);
        let now = env.ledger().timestamp();
        let mut total: i128 = 0;
        for instrument in stored.iter() {
            let core = instrument.to_core();
            if core.is_active {
                total = total
                    .checked_add(nav::instrument_value(&core, now)?)
                    .ok_or(Error::Overflow)?;
            }
        }
        Ok(total)
    }

    fn emit_nav(env: &Env) -> Result<(), Error> {
        let total = Self::total_nav(env.clone())?;
        let shares = Self::total_shares(env);
        NavUpdated {
            total_nav: total,
            nav_per_share: nav::nav_per_share(total, shares)?,
            total_shares: shares,
        }
        .publish(env);
        Ok(())
    }

    fn instruments(env: &Env) -> Vec<StoredInstrument> {
        env.storage()
            .instance()
            .get(&DataKey::Instruments)
            .unwrap_or(Vec::new(env))
    }

    fn deployed_outstanding(env: &Env) -> i128 {
        env.storage()
            .instance()
            .get(&DataKey::DeployedOutstanding)
            .unwrap_or(0)
    }

    fn set_deployed(env: &Env, value: i128) {
        env.storage()
            .instance()
            .set(&DataKey::DeployedOutstanding, &value);
    }

    /// Capital with the SPV that has not yet been recorded as an instrument.
    pub fn in_flight(env: Env) -> i128 {
        Self::deployed_outstanding(&env)
    }

    fn share(env: &Env) -> Result<ShareClient<'_>, Error> {
        let address: Address = env
            .storage()
            .instance()
            .get(&DataKey::Share)
            .ok_or(Error::NotInitialized)?;
        Ok(ShareClient::new(env, &address))
    }

    fn total_shares(env: &Env) -> i128 {
        Self::share(env).map(|s| s.total_supply()).unwrap_or(0)
    }

    fn held_by(env: &Env, who: &Address) -> i128 {
        Self::share(env).map(|s| s.balance(who)).unwrap_or(0)
    }

    fn config(env: &Env) -> Result<Config, Error> {
        env.storage()
            .instance()
            .get(&DataKey::Config)
            .ok_or(Error::NotInitialized)
    }

    fn roles(env: &Env) -> Result<Roles, Error> {
        env.storage()
            .instance()
            .get(&DataKey::Roles)
            .ok_or(Error::NotInitialized)
    }

    fn escrow(env: &Env) -> Result<EscrowClient<'_>, Error> {
        let address: Address = env
            .storage()
            .instance()
            .get(&DataKey::Escrow)
            .ok_or(Error::NotInitialized)?;
        Ok(EscrowClient::new(env, &address))
    }

    fn require_operator(env: &Env, caller: &Address) -> Result<(), Error> {
        caller.require_auth();
        bump_instance(env);
        let roles = Self::roles(env)?;
        if *caller != roles.operator && *caller != roles.admin {
            return Err(Error::Unauthorized);
        }
        Ok(())
    }

    fn require_admin(env: &Env, caller: &Address) -> Result<(), Error> {
        caller.require_auth();
        bump_instance(env);
        if *caller != Self::roles(env)?.admin {
            return Err(Error::Unauthorized);
        }
        Ok(())
    }

    fn require_spv(env: &Env, caller: &Address) -> Result<(), Error> {
        caller.require_auth();
        bump_instance(env);
        if *caller != Self::roles(env)?.spv {
            return Err(Error::Unauthorized);
        }
        Ok(())
    }
}


// ---------------------------------------------------------------- upgrades
//
// Soroban contracts replace their own bytecode; there is no proxy. So each one names an
// upgrader once — in production the timelock — and only that address can swap the code.
// The 72-hour delay and the guardian's brake live there, in front of every upgrade in the
// system.

#[contractimpl]
impl StableYieldManager {
    /// Names the contract permitted to upgrade this one. Callable once.
    ///
    /// One-way on purpose: a contract whose upgrader could be repointed has no timelock,
    /// only the appearance of one.
    pub fn bind_upgrader(env: Env, caller: Address, upgrader: Address) -> Result<(), Error> {
        Self::require_admin(&env, &caller)?;
        piron_types::upgradeable::bind(&env, &upgrader).map_err(|_| Error::AlreadyBound)
    }

    /// Replaces this contract's code. Only the bound upgrader may call it.
    pub fn upgrade(env: Env, wasm_hash: soroban_sdk::BytesN<32>) -> Result<(), Error> {
        piron_types::upgradeable::perform(&env, wasm_hash).map_err(|e| match e {
            piron_types::upgradeable::UpgradeError::NotBound => Error::NotInitialized,
            piron_types::upgradeable::UpgradeError::AlreadyBound => Error::AlreadyBound,
        })
    }

    /// Who may upgrade this contract, if anyone yet.
    pub fn upgrader(env: Env) -> Option<Address> {
        piron_types::upgradeable::upgrader(&env)
    }
}

