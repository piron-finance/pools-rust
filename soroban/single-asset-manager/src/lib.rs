/// The escrow this pool custodies through.
///
/// Declared as an interface rather than imported so the manager does not carry the
/// escrow's wasm. The escrow authorises on its manager address, which succeeds precisely
/// when this contract is the caller.
#[contractclient(name = "EscrowClient")]
pub trait Escrow {
    fn take(env: Env, from: Address, amount: i128);
    fn release(env: Env, to: Address, amount: i128);
}


/// The pool's share token. Holdings live there, not in this contract's storage, so a
/// position can be transferred, custodied or posted as collateral.
#[contractclient(name = "ShareClient")]
pub trait Share {
    fn mint(env: Env, to: Address, amount: i128);
    fn burn(env: Env, from: Address, amount: i128);
    fn balance(env: Env, id: Address) -> i128;
    fn total_supply(env: Env) -> i128;
}

#[contract]
pub struct SingleAssetManager;

#[contractimpl]
impl SingleAssetManager {
    // ------------------------------------------------------------ setup

    /// Deploys a pool with its terms fixed.
    ///
    /// Runs at deployment, so a pool can never be observed uninitialised — the EVM's
    /// initializer/reinitializer dance has no counterpart here.
    pub fn __constructor(
        env: Env,
        config: StoredConfig,
        roles: Roles,
        escrow: Address,
        share: Address,
    ) -> Result<(), Error> {
        let core_config = config.to_core()?;
        validate::validate_config(&core_config)?;

        env.storage().instance().set(&DataKey::Config, &config);
        env.storage().instance().set(&DataKey::Roles, &roles);
        env.storage().instance().set(&DataKey::Escrow, &escrow);
        env.storage().instance().set(&DataKey::Vault, &share);
        env.storage().instance().set(
            &DataKey::State,
            &StoredState {
                status: PoolStatus::Funding as u32,
                total_raised: 0,
                actual_invested: 0,
                total_discount_earned: 0,
                total_coupons_received: 0,
                total_coupons_distributed: 0,
                total_coupons_claimed: 0,
                funds_withdrawn_by_spv: 0,
                funds_returned_by_spv: 0,
                total_fees_collected: 0,
                shares_at_maturity: 0,
            },
        );
        bump_instance(&env);
        Ok(())
    }

    // ------------------------------------------------------------ funding

    /// Deposits into the pool during the funding window and mints shares 1:1.
    pub fn deposit(env: Env, investor: Address, assets: i128) -> Result<i128, Error> {
        investor.require_auth();
        bump_instance(&env);

        let data = Self::load(&env)?;
        let user = read_user(&env, &investor);
        let outcome = flow::deposit(&data, assets, env.ledger().timestamp(), user.deposit_time)?;

        // Custody first, accounting second: if the transfer fails there is nothing to
        // unwind. The investor's signature must cover this sub-invocation as well as the
        // outer call, which the transaction's auth tree handles.
        Self::escrow(&env)?.take(&investor, &assets);

        let mut state = Self::state(&env)?;
        state.total_raised = outcome.total_raised;
        Self::save_state(&env, &state);

        Self::credit_shares(&env, &investor, outcome.shares)?;

        write_user(
            &env,
            &investor,
            &storage::StoredUser {
                deposit_time: if outcome.starts_position {
                    env.ledger().timestamp()
                } else {
                    user.deposit_time
                },
                coupons_claimed: user.coupons_claimed,
                shares: user.shares.checked_add(outcome.shares).ok_or(Error::Overflow)?,
            },
        );

        Deposit {
            receiver: investor,
            assets,
            shares: outcome.shares,
        }
        .publish(&env);
        Ok(outcome.shares)
    }

    /// Marks the pool filled once the target raise is met. Permissionless — it only
    /// observes a fact anyone can verify.
    pub fn mark_filled(env: Env) -> Result<(), Error> {
        bump_instance(&env);
        let data = Self::load(&env)?;
        let status = lifecycle::mark_filled(&data)?;

        let mut state = Self::state(&env)?;
        state.status = status as u32;
        Self::save_state(&env, &state);

        PoolFilled {
            total_raised: state.total_raised,
            timestamp: env.ledger().timestamp(),
        }
        .publish(&env);
        Ok(())
    }

    /// Closes the funding epoch: on to investment, or to emergency if underfunded.
    pub fn close_epoch(env: Env, caller: Address) -> Result<u32, Error> {
        Self::require_role(&env, &caller, RoleKind::Operator)?;
        Self::close(env, false)
    }

    /// Admin close that skips the epoch-end check.
    pub fn force_close_epoch(env: Env, caller: Address) -> Result<u32, Error> {
        Self::require_role(&env, &caller, RoleKind::Admin)?;
        Self::close(env, true)
    }

    // ------------------------------------------------------------ investment

    /// Records funds released to the SPV for investment.
    pub fn withdraw_for_investment(env: Env, caller: Address, amount: i128) -> Result<(), Error> {
        Self::require_role(&env, &caller, RoleKind::Spv)?;

        let data = Self::load(&env)?;
        lifecycle::validate_spv_withdrawal(&data, amount)?;

        let mut state = Self::state(&env)?;
        state.funds_withdrawn_by_spv = state
            .funds_withdrawn_by_spv
            .checked_add(amount)
            .ok_or(Error::Overflow)?;
        Self::save_state(&env, &state);

        Self::escrow(&env)?.release(&caller, &amount);
        SPVFundsWithdrawn { amount }.publish(&env);
        Ok(())
    }

    /// Confirms what the SPV deployed, fixing face value and the discount to accrue.
    pub fn confirm_investment(
        env: Env,
        caller: Address,
        actual_amount: i128,
        proof_hash: String,
    ) -> Result<(), Error> {
        Self::require_role(&env, &caller, RoleKind::Spv)?;

        let data = Self::load(&env)?;
        let outcome =
            lifecycle::process_investment(&data, actual_amount, env.ledger().timestamp())?;

        let mut state = Self::state(&env)?;
        state.status = outcome.new_status as u32;
        state.actual_invested = outcome.actual_invested;
        state.total_discount_earned = outcome.total_discount_earned;
        Self::save_state(&env, &state);

        let mut config: StoredConfig = Self::config(&env)?;
        config.face_value = outcome.face_value;
        env.storage().instance().set(&DataKey::Config, &config);

        InvestmentConfirmed {
            actual_amount,
            proof_hash,
        }
        .publish(&env);
        Ok(())
    }

    // ------------------------------------------------------------ coupons

    /// Records a coupon received from the SPV.
    pub fn record_coupon(env: Env, caller: Address, amount: i128) -> Result<(), Error> {
        Self::require_role(&env, &caller, RoleKind::Spv)?;

        let data = Self::load(&env)?;
        validate::validate_coupon_payment(&data, amount)?;

        Self::escrow(&env)?.take(&caller, &amount);

        let mut state = Self::state(&env)?;
        state.total_coupons_received = state
            .total_coupons_received
            .checked_add(amount)
            .ok_or(Error::Overflow)?;
        Self::save_state(&env, &state);

        CouponReceived {
            amount,
            total_received: state.total_coupons_received,
        }
        .publish(&env);
        Ok(())
    }

    /// Makes received coupons claimable by holders.
    pub fn distribute_coupons(env: Env, caller: Address) -> Result<i128, Error> {
        Self::require_role(&env, &caller, RoleKind::Operator)?;

        let data = Self::load(&env)?;
        let total_shares = Self::total_shares(&env);
        let amount = calc::distributable_coupons(&data, total_shares)?;

        let mut state = Self::state(&env)?;
        state.total_coupons_distributed = state.total_coupons_received;
        Self::save_state(&env, &state);

        CouponDistributed { amount }.publish(&env);
        Ok(amount)
    }

    /// Claims a holder's share of distributed coupons.
    pub fn claim_coupon(env: Env, holder: Address) -> Result<i128, Error> {
        holder.require_auth();
        bump_instance(&env);

        let data = Self::load(&env)?;
        let mut user = read_user(&env, &holder);
        let claim = calc::claim_coupon(
            &data,
            // Subscribed shares, not the live balance — see `StoredUser::shares`.
            user.shares,
            Self::total_shares(&env),
            user.coupons_claimed,
        )?;

        user.coupons_claimed = claim.new_claimed_total;
        write_user(&env, &holder, &user);

        let mut state = Self::state(&env)?;
        state.total_coupons_claimed = state
            .total_coupons_claimed
            .checked_add(claim.claimable)
            .ok_or(Error::Overflow)?;
        Self::save_state(&env, &state);

        Self::escrow(&env)?.release(&holder, &claim.claimable);
        CouponClaimed {
            holder,
            claimable: claim.claimable,
        }
        .publish(&env);
        Ok(claim.claimable)
    }

    // ------------------------------------------------------------ maturity

    /// Settles the deal with the amount the SPV returned.
    pub fn settle_maturity(env: Env, caller: Address, final_amount: i128) -> Result<(), Error> {
        Self::require_role(&env, &caller, RoleKind::Spv)?;

        let data = Self::load(&env)?;
        let outcome = lifecycle::process_maturity(
            &data,
            final_amount,
            env.ledger().timestamp(),
            Self::total_shares(&env),
        )?;

        Self::escrow(&env)?.take(&caller, &final_amount);

        let mut state = Self::state(&env)?;
        state.status = outcome.new_status as u32;
        state.funds_returned_by_spv = outcome.funds_returned;
        state.shares_at_maturity = outcome.shares_at_maturity;
        Self::save_state(&env, &state);

        let expected = lifecycle::expected_settlement(&data);
        match outcome.variance {
            lifecycle::MaturityVariance::Shortfall(gap) => MaturityShortfall {
                expected,
                actual: final_amount,
                shortfall: gap,
            }
            .publish(&env),
            lifecycle::MaturityVariance::Overage => MaturityOverage {
                expected,
                actual: final_amount,
            }
            .publish(&env),
            lifecycle::MaturityVariance::OnTarget => {}
        }

        MaturityProcessed { final_amount }.publish(&env);
        Ok(())
    }

    /// Redeems a holder's position. Which path applies depends on the pool's status.
    pub fn withdraw(env: Env, owner: Address, assets: i128) -> Result<i128, Error> {
        owner.require_auth();
        bump_instance(&env);

        let data = Self::load(&env)?;
        let user_shares = Self::held_by(&env, &owner);
        let outcome = flow::withdraw(
            &data,
            flow::WithdrawRequest {
                assets,
                user_shares,
                total_shares: Self::total_shares(&env),
                now: env.ledger().timestamp(),
            },
        )?;

        // Struck before the burn: `claim_coupon` divides by total supply, and burning
        // first would shrink the denominator and overstate what is owed.
        let mut user = read_user(&env, &owner);
        let owed = calc::available_coupon(
            &data,
            user.shares,
            Self::total_shares(&env),
            user.coupons_claimed,
        );

        Self::debit_shares(&env, &owner, outcome.shares_burned)?;

        let mut state = Self::state(&env)?;
        state.total_raised = outcome.total_raised;
        state.total_fees_collected = state
            .total_fees_collected
            .checked_add(outcome.fee)
            .ok_or(Error::Overflow)?;
        Self::save_state(&env, &state);

        // Distributed coupons are earmarked in custody and excluded from the settlement
        // pot, so a holder who never got round to claiming would otherwise leave the
        // money reachable by nobody at all.
        if owed > 0 {
            user.coupons_claimed = user
                .coupons_claimed
                .checked_add(owed)
                .ok_or(Error::Overflow)?;
            let mut with_coupon = Self::state(&env)?;
            with_coupon.total_coupons_claimed = with_coupon
                .total_coupons_claimed
                .checked_add(owed)
                .ok_or(Error::Overflow)?;
            Self::save_state(&env, &with_coupon);
        }

        user.shares = (user.shares - outcome.shares_burned).max(0);
        if outcome.clears_position {
            user.deposit_time = 0;
            user.coupons_claimed = 0;
            user.shares = 0;
        }
        write_user(&env, &owner, &user);

        let escrow = Self::escrow(&env)?;
        if owed > 0 {
            escrow.release(&owner, &owed);
        }
        escrow.release(&owner, &outcome.net);
        if outcome.fee > 0 {
            escrow.release(&Self::roles(&env)?.treasury, &outcome.fee);
        }

        Withdraw {
            owner: owner.clone(),
            assets: outcome.net,
            shares: outcome.shares_burned,
        }
        .publish(&env);

        if outcome.fee > 0 {
            WithdrawalFeeCollected {
                user: owner,
                fee_amount: outcome.fee,
                net_amount: outcome.net,
            }
            .publish(&env);
        }
        Ok(outcome.net)
    }

    /// Closes a fully-redeemed pool.
    pub fn mark_withdrawn(env: Env, caller: Address) -> Result<(), Error> {
        Self::require_role(&env, &caller, RoleKind::Operator)?;

        let data = Self::load(&env)?;
        let status = lifecycle::mark_withdrawn(&data, Self::total_shares(&env))?;

        let mut state = Self::state(&env)?;
        state.status = status as u32;
        Self::save_state(&env, &state);

        PoolFullyWithdrawn {
            timestamp: env.ledger().timestamp(),
        }
        .publish(&env);
        Ok(())
    }

    /// Halts the pool and opens refunds.
    pub fn declare_emergency(env: Env, caller: Address, trigger: String) -> Result<(), Error> {
        Self::require_role(&env, &caller, RoleKind::Emergency)?;

        let data = Self::load(&env)?;
        let status = lifecycle::declare_emergency(&data)?;

        let mut state = Self::state(&env)?;
        state.status = status as u32;
        Self::save_state(&env, &state);

        EmergencyStateChanged {
            trigger,
            total_amount: state.total_raised,
            timestamp: env.ledger().timestamp(),
        }
        .publish(&env);
        Ok(())
    }

    // ------------------------------------------------------------ views

    pub fn pool_value(env: Env) -> Result<i128, Error> {
        let data = Self::load(&env)?;
        Ok(calc::current_pool_value(&data, env.ledger().timestamp())?)
    }

    pub fn user_return(env: Env, who: Address) -> Result<i128, Error> {
        let data = Self::load(&env)?;
        Ok(calc::user_return(
            &data,
            Self::held_by(&env, &who),
            Self::total_shares(&env),
            env.ledger().timestamp(),
        )?)
    }

    pub fn available_coupon(env: Env, who: Address) -> Result<i128, Error> {
        let data = Self::load(&env)?;
        let user = read_user(&env, &who);
        Ok(calc::available_coupon(
            &data,
            user.shares,
            Self::total_shares(&env),
            user.coupons_claimed,
        ))
    }

    /// Convenience passthrough; the token is the source of truth.
    pub fn shares_of(env: Env, who: Address) -> i128 {
        Self::held_by(&env, &who)
    }

    pub fn share_token(env: Env) -> Result<Address, Error> {
        env.storage()
            .instance()
            .get(&DataKey::Vault)
            .ok_or(Error::NotInitialized)
    }

    pub fn total_supply(env: Env) -> i128 {
        Self::total_shares(&env)
    }

    pub fn escrow_address(env: Env) -> Result<Address, Error> {
        env.storage()
            .instance()
            .get(&DataKey::Escrow)
            .ok_or(Error::NotInitialized)
    }

    pub fn status(env: Env) -> Result<u32, Error> {
        Ok(Self::state(&env)?.status)
    }

    // ------------------------------------------------------------ internals

    fn close(env: Env, force: bool) -> Result<u32, Error> {
        bump_instance(&env);
        let data = Self::load(&env)?;
        let close = lifecycle::close_epoch(&data, env.ledger().timestamp(), force)?;

        let mut state = Self::state(&env)?;
        state.status = close.new_status as u32;
        Self::save_state(&env, &state);

        let mut config = Self::config(&env)?;
        config.face_value = close.face_value;
        env.storage().instance().set(&DataKey::Config, &config);

        if close.underfunded {
            EmergencyStateChanged {
                trigger: String::from_str(&env, "UNDERFUNDED_EPOCH"),
                total_amount: state.total_raised,
                timestamp: env.ledger().timestamp(),
            }
            .publish(&env);
        }

        EpochClosed {
            new_status: close.new_status as u32,
            total_raised: state.total_raised,
            face_value: close.face_value,
        }
        .publish(&env);
        Ok(close.new_status as u32)
    }

    fn share(env: &Env) -> Result<ShareClient<'_>, Error> {
        let address: Address = env
            .storage()
            .instance()
            .get(&DataKey::Vault)
            .ok_or(Error::NotInitialized)?;
        Ok(ShareClient::new(env, &address))
    }

    fn credit_shares(env: &Env, who: &Address, amount: i128) -> Result<(), Error> {
        Self::share(env)?.mint(who, &amount);
        Ok(())
    }

    fn debit_shares(env: &Env, who: &Address, amount: i128) -> Result<(), Error> {
        Self::share(env)?.burn(who, &amount);
        Ok(())
    }

    fn total_shares(env: &Env) -> i128 {
        Self::share(env).map(|s| s.total_supply()).unwrap_or(0)
    }

    fn held_by(env: &Env, who: &Address) -> i128 {
        Self::share(env).map(|s| s.balance(who)).unwrap_or(0)
    }

    fn require_role(env: &Env, caller: &Address, kind: RoleKind) -> Result<(), Error> {
        caller.require_auth();
        bump_instance(env);
        let roles = Self::roles(env)?;
        let expected = match kind {
            RoleKind::Admin => roles.admin,
            RoleKind::Operator => roles.operator,
            RoleKind::Spv => roles.spv,
            RoleKind::Emergency => roles.emergency,
        };
        if *caller != expected {
            return Err(Error::Unauthorized);
        }
        Ok(())
    }

    fn escrow(env: &Env) -> Result<EscrowClient<'_>, Error> {
        let address: Address = env
            .storage()
            .instance()
            .get(&DataKey::Escrow)
            .ok_or(Error::NotInitialized)?;
        Ok(EscrowClient::new(env, &address))
    }

    fn roles(env: &Env) -> Result<Roles, Error> {
        env.storage()
            .instance()
            .get(&DataKey::Roles)
            .ok_or(Error::NotInitialized)
    }

    fn config(env: &Env) -> Result<StoredConfig, Error> {
        env.storage()
            .instance()
            .get(&DataKey::Config)
            .ok_or(Error::NotInitialized)
    }

    fn state(env: &Env) -> Result<StoredState, Error> {
        env.storage()
            .instance()
            .get(&DataKey::State)
            .ok_or(Error::NotInitialized)
    }

    fn save_state(env: &Env, state: &StoredState) {
        env.storage().instance().set(&DataKey::State, state);
    }

    /// Assembles the core view of the pool from storage.
    fn load(env: &Env) -> Result<PoolData, Error> {
        let config = Self::config(env)?;
        let state = Self::state(env)?;
        Ok(PoolData {
            config: config.to_core()?,
            status: status_from_u32(state.status),
            total_raised: state.total_raised,
            actual_invested: state.actual_invested,
            total_discount_earned: state.total_discount_earned,
            total_coupons_received: state.total_coupons_received,
            total_coupons_distributed: state.total_coupons_distributed,
            total_coupons_claimed: state.total_coupons_claimed,
            funds_withdrawn_by_spv: state.funds_withdrawn_by_spv,
            funds_returned_by_spv: state.funds_returned_by_spv,
            total_fees_collected: state.total_fees_collected,
            shares_at_maturity: state.shares_at_maturity,
        })
    }
}

enum RoleKind {
    Admin,
    Operator,
    Spv,
    Emergency,
}

/// Numeric values match the Solidity `PoolStatus` enum ordering.
fn status_from_u32(value: u32) -> PoolStatus {
    match value {
        0 => PoolStatus::Funding,
        1 => PoolStatus::Filled,
        2 => PoolStatus::PendingInvestment,
        3 => PoolStatus::Invested,
        4 => PoolStatus::Matured,
        5 => PoolStatus::Withdrawn,
        _ => PoolStatus::Emergency,
    }
}


// ---------------------------------------------------------------- upgrades
//
// Soroban contracts replace their own bytecode; there is no proxy. So each one names an
// upgrader once — in production the timelock — and only that address can swap the code.
// The 72-hour delay and the guardian's brake live there, in front of every upgrade in the
// system.

#[contractimpl]
impl SingleAssetManager {
    /// Names the contract permitted to upgrade this one. Callable once.
    ///
    /// One-way on purpose: a contract whose upgrader could be repointed has no timelock,
    /// only the appearance of one.
    pub fn bind_upgrader(env: Env, caller: Address, upgrader: Address) -> Result<(), Error> {
        Self::require_role(&env, &caller, RoleKind::Admin)?;
        piron_types::upgradeable::bind(&env, &upgrader).map_err(|_| Error::AlreadyBound)
    }

    /// Replaces this contract's code. Only the bound upgrader may call it.
    pub fn upgrade(env: Env, wasm_hash: soroban_sdk::BytesN<32>) -> Result<(), Error> {
        piron_types::upgradeable::perform(&env, wasm_hash).map_err(|e| match e {
            piron_types::upgradeable::UpgradeError::NotBound => Error::NotInitialized,
            piron_types::upgradeable::UpgradeError::AlreadyBound => Error::AlreadyBound,
        })
    }

    /// Who may upgrade this contract, if anyone yet.
    pub fn upgrader(env: Env) -> Option<Address> {
        piron_types::upgradeable::upgrader(&env)
    }
}

