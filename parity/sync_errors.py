#!/usr/bin/env python3
"""Regenerate each Soroban binding's error enum from `piron_core::Error`.

One taxonomy, three runtimes: a condition must report the same number everywhere, or the
backend cannot map errors with one table. The bindings declare a `#[contracterror]` enum
whose variants mirror core's exactly, plus their own binding-only codes from 600 up.

Core's `From` impl is deliberately exhaustive, so adding a core error breaks every binding
build until it is mapped. That is the intended alarm — this script is how you answer it.

    python3 parity/sync_errors.py           # rewrite the bindings
    python3 parity/sync_errors.py --check   # exit 1 if any is stale
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CORE = ROOT / "crates/piron-core/src/error.rs"
BINDINGS = [
    ROOT / "soroban/single-asset-manager/src/lib.rs",
    ROOT / "soroban/locked-pool-manager/src/lib.rs",
    ROOT / "soroban/stable-yield-manager/src/lib.rs",
]

VARIANT = re.compile(r"^\s{4}([A-Z]\w+) = (\d+),", re.M)
BLOCK = re.compile(
    r"#\[contracterror\].*?impl From<piron_core::Error> for Error \{.*?\n\}\n",
    re.S,
)


# Codes at or above this are the bindings' own and are never generated from core.
LOCAL_CODE_FLOOR = 700


def core_variants() -> list[tuple[str, int]]:
    variants = [(n, int(c)) for n, c in VARIANT.findall(CORE.read_text())]
    trespassing = [n for n, c in variants if c >= LOCAL_CODE_FLOOR]
    if trespassing:
        sys.exit(
            f"core uses codes at or above {LOCAL_CODE_FLOOR}, which are reserved for "
            f"binding-only errors: {', '.join(trespassing)}"
        )
    return variants


def render(core: list[tuple[str, int]], local: list[tuple[str, str]]) -> str:
    enum_lines = "\n".join(f"    {n} = {c}," for n, c in core)
    local_lines = "\n".join(local)
    from_lines = "\n".join(
        f"            piron_core::Error::{n} => Error::{n}," for n, _ in core
    )
    return (
        "#[contracterror]\n"
        "#[derive(Copy, Clone, Debug, PartialEq, Eq)]\n"
        "#[repr(u32)]\n"
        "pub enum Error {\n"
        f"{enum_lines}\n"
        f"{local_lines}\n"
        "}\n\n"
        "impl From<piron_core::Error> for Error {\n"
        "    /// Generated by `parity/sync_errors.py`. Exhaustive by design: a new core\n"
        "    /// error breaks this build until it is mapped, which is what keeps one\n"
        "    /// taxonomy across EVM, Stellar and Solana.\n"
        "    fn from(err: piron_core::Error) -> Self {\n"
        "        match err {\n"
        f"{from_lines}\n"
        "        }\n"
        "    }\n"
        "}\n"
    )


def main() -> int:
    check = "--check" in sys.argv
    core = core_variants()
    stale = []

    for path in BINDINGS:
        src = path.read_text()
        match = BLOCK.search(src)
        if not match:
            sys.exit(f"no error block found in {path}")

        # Binding-only codes (700+) are hand-written; carry them across untouched.
        # Scoped to the enum body so the `From` impl's own doc comments are not dragged
        # in and left dangling at the end of the enum.
        body = match.group(0)
        enum_body = body[body.index("pub enum Error {") : body.index("\n}\n\nimpl From")]
        local = [
            line
            for line in enum_body.splitlines()
            if re.match(r"^\s{4}(///|[A-Z]\w+ = [7-9]\d\d,)", line)
        ]

        rebuilt = src[: match.start()] + render(core, local) + src[match.end() :]
        if rebuilt == src:
            continue
        stale.append(path.relative_to(ROOT).as_posix())
        if not check:
            path.write_text(rebuilt)

    if check:
        if stale:
            print("stale error enums:\n  " + "\n  ".join(stale))
            return 1
        print(f"In sync — {len(core)} core errors mirrored in {len(BINDINGS)} bindings.")
        return 0

    if stale:
        print(f"Updated {len(stale)} binding(s) to {len(core)} core errors:")
        for s in stale:
            print(f"  {s}")
    else:
        print(f"Already in sync — {len(core)} core errors.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
