//! Single-Asset pool manager — Soroban binding.
//!
//! Holds **no protocol decisions**. Every rule lives in `piron-core`; each entry point
//! authorises the caller, extends TTL, delegates, persists the outcome and emits an event.
//! If you find an `if` here that a chain could disagree with, it is in the wrong crate.
//!
//! Share balances are kept in this contract for now. On EVM they live in the ERC-4626
//! `LiquidityPool`; moving them into an OpenZeppelin `Vault` is task S5.

